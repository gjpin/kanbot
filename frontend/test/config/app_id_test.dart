import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:kanbot/config/app_id.dart';

/// The platform projects carry the same application ID as the Dart code:
/// a mismatch breaks the login handoff on that platform.
void main() {
  String read(String path) => File(path).readAsStringSync();

  test('the app redirect uses the application ID as its scheme', () {
    expect(appRedirectUri, 'dev.sideral.kanbot:/auth/done');
    expect(Uri.parse(appRedirectUri).scheme, applicationId);
  });

  test('Android', () {
    final gradle = read('android/app/build.gradle.kts');
    expect(gradle, contains('namespace = "$applicationId"'));
    expect(gradle, contains('applicationId = "$applicationId"'));
    final manifest = read('android/app/src/main/AndroidManifest.xml');
    // The only scheme the app receives: the login handoff.
    final filters = RegExp(r'<intent-filter[\s\S]*?</intent-filter>')
        .allMatches(manifest)
        .map((match) => match.group(0) ?? '');
    expect(
      filters
          .expand(RegExp('android:scheme="([^"]+)"').allMatches)
          .map((match) => match.group(1)),
      [applicationId],
    );
    expect(
      File('android/app/src/main/kotlin/dev/sideral/kanbot/MainActivity.kt')
          .readAsStringSync(),
      startsWith('package $applicationId\n'),
    );
  });

  test('iOS and macOS', () {
    final ios = read('ios/Runner.xcodeproj/project.pbxproj');
    expect(
      RegExp(r'PRODUCT_BUNDLE_IDENTIFIER = ([^;]+);')
          .allMatches(ios)
          .map((match) => match.group(1))
          .toSet(),
      {applicationId, '$applicationId.RunnerTests'},
    );
    expect(
      read('macos/Runner/Configs/AppInfo.xcconfig'),
      contains('PRODUCT_BUNDLE_IDENTIFIER = $applicationId\n'),
    );
  });

  test('Linux', () {
    expect(
      read('linux/CMakeLists.txt'),
      contains('set(APPLICATION_ID "$applicationId")'),
    );
  });

  test('no platform keeps the template ID', () {
    for (final dir in ['android', 'ios', 'macos', 'linux', 'windows', 'web']) {
      for (final file in Directory(
        dir,
      ).listSync(recursive: true, followLinks: false)) {
        // ephemeral/: generated by the Flutter tool, not committed.
        if (file is! File ||
            !_isText(file.path) ||
            file.uri.pathSegments.contains('ephemeral')) {
          continue;
        }
        expect(
          file.readAsStringSync(),
          isNot(contains('com.example')),
          reason: file.path,
        );
      }
    }
  });
}

bool _isText(String path) => [
  '.kts',
  '.xml',
  '.kt',
  '.pbxproj',
  '.xcconfig',
  '.txt',
  '.rc',
  '.plist',
  '.json',
  '.html',
  '.cc',
  '.h',
  '.cmake',
  '.swift',
].any(path.endsWith);
